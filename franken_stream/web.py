def _enrich(item: dict) -> dict:
    """Pass-through enrichment hook for search results."""
    return item


@web_app.post("/api/v1/search")
async def v1_search(request: Request):
    data = await request.json()
    query = data.get("query", "").strip()
    if not query:
        raise HTTPException(status_code=400, detail="query is required")

    # FTS5 cache check
    fts = FTSCache()
    cached = fts.lookup(query)
    if cached:
        results = [_enrich({"title": t, "url": u}) for t, u in cached]
        asyncio.create_task(_get_preloader().preload(cached[:3]))
        return {"status": "ok", "query": query, "results": results, "cached": True}

    pm = ProviderManager()
    scraper = AsyncContentScraper(provider_manager=pm)
    try:
        bases = pm.get_ranked_search_bases()
        scraper_results, plugin_results = await asyncio.gather(
            scraper.search(query, bases),
            pm.search_plugins(query),
            return_exceptions=True,
        )
        if isinstance(scraper_results, Exception):
            scraper_results = []
        if isinstance(plugin_results, Exception):
            plugin_results = []

        # Merge all results, score by relevance, deduplicate by URL
        from franken_stream.async_scraper import _relevance_score
        seen: set = set()
        scored = []
        for title, url in scraper_results:
            if url not in seen:
                seen.add(url)
                scored.append((_relevance_score(title, query), title, url))
        for item in plugin_results:
            # plugin_results are MediaItem objects
            title = getattr(item, "title", "") if not isinstance(item, tuple) else item[0]
            url = getattr(item, "url", "") if not isinstance(item, tuple) else item[1]
            if url and url not in seen:
                seen.add(url)
                scored.append((_relevance_score(title, query), title, url))

        # Best matches first
        scored.sort(key=lambda x: (-x[0], x[1]))
        raw = [(t, u) for _, t, u in scored]

        if raw:
            fts.store(query, raw)
        asyncio.create_task(_get_preloader().preload(raw[:3]))
        results = [_enrich({"title": t, "url": u}) for t, u in raw]
        return {"status": "ok", "query": query, "results": results, "cached": False}
    finally:
        await scraper.close()


@web_app.post("/api/search")
async def search(request: Request):
    """Search for movies/shows"""
    try:
        data = await request.json()
        query = data.get("query", "").strip()

        if not query:
            raise HTTPException(status_code=400, detail="Query is required")

        # FTS5 cache check
        fts = FTSCache()
        cached = fts.lookup(query)
        if cached:
            return {
                "status": "ok",
                "query": query,
                "results": [{"title": t, "url": u} for t, u in cached],
                "cached": True,
            }

        pm = ProviderManager()
        scraper = AsyncContentScraper(provider_manager=pm)
        try:
            bases = pm.get_ranked_search_bases()
            raw = await scraper.search(query, bases)
            if raw:
                fts.store(query, raw)
            return {
                "status": "ok",
                "query": query,
                "results": [{"title": title, "url": url} for title, url in raw],
                "cached": False,
            }
        finally:
            await scraper.close()
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


