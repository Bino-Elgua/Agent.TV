@web_app.get("/api/v1/poster")
async def v1_poster(title: str, year: Optional[str] = None):
    """
    Return a poster image URL for a movie/show title.
    Requires TMDB_API_KEY env var. Returns null poster_url if unavailable.
    """
    import aiohttp as _aio
    tmdb_key = os.environ.get("TMDB_API_KEY", "")
    if not tmdb_key:
        return {"poster_url": None, "source": "none"}

    try:
        params: dict = {"api_key": tmdb_key, "query": title, "page": 1}
        if year:
            params["year"] = year
        async with _aio.ClientSession() as s:
            async with s.get(
                "https://api.themoviedb.org/3/search/multi",
                params=params,
                timeout=_aio.ClientTimeout(total=5),
            ) as r:
                if r.status == 200:
                    data = await r.json()
                    for item in data.get("results", [])[:4]:
                        poster = item.get("poster_path")
                        if poster:
                            return {
                                "poster_url": f"https://image.tmdb.org/t/p/w342{poster}",
                                "source": "tmdb",
                            }
    except Exception:
        pass

    return {"poster_url": None, "source": "none"}


@web_app.post("/api/v1/play")
async def v1_play(request: Request):
    data = await request.json()
    url = data.get("url", "").strip()
    title = data.get("title", "")
    if not url:
        raise HTTPException(status_code=400, detail="url is required")

    # Attempt Real-Debrid unrestriction if configured
    rd = get_rd_client()
    if rd is not None:
        try:
            premium = await rd.unrestrict(url)
            if premium:
                url = premium
        except Exception:
            pass

    result = await _player.play(url, title=title)
    if result.get("status") == "playing":
        media_id = hashlib.md5(url.encode()).hexdigest()[:12]
        _watchlist.add(media_id, title or url, url)
    await _broadcast({"type": "playback", "event": "started", **result})
    return result


@web_app.post("/api/v1/control")
async def v1_control(request: Request):
    data = await request.json()
    action = data.get("action", "")
    ok = False

    if action == "pause":
        ok = await _player.pause()
    elif action == "resume":
        ok = await _player.resume()
    elif action == "stop":
        await _player.stop()
        ok = True
    elif action == "seek":
        position = data.get("position")
        if position is None:
            raise HTTPException(status_code=400, detail="position required for seek")
        ok = await _player.seek(int(position))
    else:
        raise HTTPException(status_code=400, detail=f"Unknown action: {action}")

    await _broadcast({"type": "playback", "event": action, "ok": ok})
    return {"action": action, "ok": ok}


